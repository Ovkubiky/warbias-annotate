"""Build docs/sample-data.js: a small slice of real WarBias cards for the demo mode.

Mirrors importWarBias() in apps-script/Code.js, so the demo shows exactly what the
real backend would serve. Usage: python3 scripts/build_sample.py
"""
import json
import random
import urllib.request
from pathlib import Path

BASE = "https://huggingface.co/datasets/FairForget/WarBias/resolve/main/"
OUT = Path(__file__).resolve().parent.parent / "docs" / "sample-data.js"


def get(path):
    with urllib.request.urlopen(BASE + path) as r:
        return r.read().decode("utf-8")


def jsonl(path):
    return [json.loads(line) for line in get(path).splitlines() if line.strip()]


def main():
    uk = jsonl("data/uk/unassigned.jsonl")
    en = {r["id"]: r for r in jsonl("data/en/unassigned.jsonl")}
    qa_uk = jsonl("data/eval_uk/unassigned.jsonl")
    qa_en = {r["id"]: r for r in jsonl("data/eval_en/unassigned.jsonl")}
    cases = {r["case_id"]: r for r in jsonl("metadata/cases.jsonl")}
    tags = {t["id"]: t["definition"] for t in json.loads(get("metadata/tags.json"))["bias_tags"]}

    items = []
    for r in uk:
        e, cs = en.get(r["id"], {}), cases.get(r["case_id"], {})
        items.append({"item_id": r["id"], "type": "tri", "gold": "", "payload": {
            "actor": r["actor"], "section": cs.get("source_section_uk", ""), "def_en": tags.get(r["bias_tags"][0], ""),
            "S": r["stereotype"], "C": r["counter_stereotype"], "U": r["unrelated"],
            "eS": e.get("stereotype", ""), "eC": e.get("counter_stereotype", ""), "eU": e.get("unrelated", "")}})
    for q in qa_uk:
        e = qa_en.get(q["id"], {})
        items.append({"item_id": q["id"], "type": "qa", "gold": "", "payload": {
            "actor": q["target_group"], "ctx": q["context"], "q": q["question"], "ch": q["choices"],
            "en": {"ctx": e.get("context", ""), "q": e.get("question", ""), "ch": e.get("choices", [])}}})
    fam = {}
    for r in uk:
        f = fam.setdefault(r["case_id"], {"actor": r["actor"], "tag": r["bias_tags"][0], "plain": [], "other": []})
        (f["other"] if r.get("reporter") else f["plain"]).append(r["stereotype"])
    for cid in sorted(fam):
        f, cs = fam[cid], cases.get(cid, {})
        ex = list(dict.fromkeys(f["plain"] + f["other"]))[:3]
        items.append({"item_id": cid, "type": "sev", "gold": "", "payload": {
            "actor": f["actor"], "section": cs.get("source_section_uk", ""), "def_en": tags.get(f["tag"], ""), "ex": ex}})

    counts = {t: sum(1 for i in items if i["type"] == t) for t in ("tri", "qa", "sev")}
    print("full import would create:", counts, "total", len(items))

    rnd = random.Random(7)
    sample = []
    for t, n in (("tri", 14), ("qa", 6), ("sev", 6)):
        sample += rnd.sample([i for i in items if i["type"] == t], n)
    OUT.write_text("// Generated by scripts/build_sample.py from FairForget/WarBias. Demo mode only.\n"
                   "window.WB_SAMPLE = " + json.dumps(sample, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
    print("wrote", OUT, len(sample), "cards")


if __name__ == "__main__":
    main()
